use dateparser::parse;
use std::error::Error;

fn main() -> Result<(), Box<dyn Error>> {
    let dates = vec![
        "2010:06:24",
        "2017:08:16 12:18:36",
        "2017:08:16T12:18:36",
        "2017:06:17 18:01:24pm",
        "2017:06:17 18:01:24PM",
        "2019:05:23 06:10:21.000 UTC",
        "2002/08/29 17:31:40",
        "2022-04-02T08:20:27",
        "2018-06-30T13:02:35.003",
        "2018-06-30T17:11",
        "8/16/17 12:18 PM",
        "Wed Nov 30 05:58:56 +01:00 2022",
        "Wed Jan 18 13:10:27 CST 2023",
        "2002-06-20",
        "2022-01-31T23:59:15+0800",
        "2015-01-22T00:00:00 +00:00",
        "2012-05-22T15:52:27+01:00",
        "2012-12-31T04:35:10Z",
        "Tue May 7 21:48:30 2002",
        "2018-07-01T20:38+08:00",
    ];
    for date in dates {
        println!("-> test {}", date);
        let parsed = parse(date).unwrap();
        println!("{:#?}", parsed);
    }
    Ok(())
}
